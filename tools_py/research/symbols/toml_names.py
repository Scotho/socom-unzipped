def elf_sections(path):
    b = open(path, "rb").read()
    phoff, = struct.unpack_from("<I", b, 28)
    phnum, = struct.unpack_from("<H", b, 44)
    shnum, = struct.unpack_from("<H", b, 48)
    entry, = struct.unpack_from("<I", b, 24)
    secs = []  # AppendLoadSegmentsAsSections: file-backed part of each PT_LOAD; code iff PF_X
    for i in range(phnum):
        t, off, va, _pa, fs, ms, fl, _al = struct.unpack_from("<8I", b, phoff + 32 * i)
        if t == 1 and fs:
            secs.append((va, fs, bool(fl & 1), off))
    secs.sort()
    return b, secs, entry, shnum


def replay(elf_path, rows):
    b, secs, entry, shnum = elf_sections(elf_path)
    code = [(va, va + fs, off) for va, fs, x, off in secs if x]

    def code_sec(a):
        for lo, hi, _o in code:
            if lo <= a < hi:
                return lo, hi
        return None

    def clamp(sec, start, end):
        hi = sec[1]
        if end == 0 or end > hi:
            end = hi
        if end <= start:
            end = start + 4 if start + 4 <= hi else hi
        return end

    # ScanJalTargetsFallback (no DWARF, no section headers in the synthetic ELF)
    starts = set()
    if code_sec(entry):
        starts.add(entry)
    for lo, hi, off in code:
        for o in range(0, hi - lo - 3, 4):
            w, = struct.unpack_from("<I", b, off + o)
            if w >> 26 == 3:
                tgt = ((lo + o + 4) & 0xF0000000) | ((w & 0x03FFFFFF) << 2)
                if code_sec(tgt):
                    starts.add(tgt)
    ss = sorted(starts)
    extras = []
    for i, s in enumerate(ss):
        sec = code_sec(s)
        end = sec[1]
        if i + 1 < len(ss) and s < ss[i + 1] < sec[1]:
            end = ss[i + 1]
        extras.append(("sub_%08X" % s, s, end if end > s else s + 4))
    jal_end = {s: e for _n, s, e in extras}

    # loadGhidraFunctionMap
    map_starts = set()
    for name, s, e in rows:
        sec = code_sec(s)
        if not sec:
            continue
        e = clamp(sec, s, e)
        if e <= s:
            continue
        extras.append((name, s, e))
        map_starts.add(s)
    extras = [f for f in extras if not (is_auto(f[0]) and f[1] not in map_starts)]
    extras.sort(key=lambda f: (f[1], is_auto(f[0]), -f[2], f[0]))
    uniq, seen = [], set()
    for f in extras:
        if f[1] not in seen:
            seen.add(f[1])
            uniq.append(f)

    # extractFunctions (no ELF symbols: only the map/fallback extras)
    auth = {}
    for name, s, e in uniq:
        if s and e > s and name and not is_auto(name) and code_sec(s):
            auth[s] = max(auth.get(s, 0), clamp(code_sec(s), s, e))
    ranges = sorted(auth.items())
    rstarts = [r[0] for r in ranges]

    def inside_auth(s):
        i = bisect.bisect_right(rstarts, s)
        if i == 0:
            return False
        lo, hi = ranges[i - 1]
        return lo < s < hi

    funcs, dropped = [], []
    for name, s, e in uniq:
        if not code_sec(s):
            continue
        if inside_auth(s) and (s not in auth or is_auto(name)):
            dropped.append((name, s))
            continue
        funcs.append((name, s, auth.get(s, e)))
    funcs.sort(key=lambda f: f[1])
    return funcs, dropped, jal_end, shnum, entry


def word_reader(elf_path):
    b, secs, _entry, _shnum = elf_sections(elf_path)

    def word(a):
        for va, fs, _x, off in secs:
            if va <= a < va + fs:
                return struct.unpack_from("<I", b, off + a - va)[0]
        return None
    return word


def branch_target(pc, w):
    """Static branch/jump target of the R5900 word at pc (calls excluded), else None."""
    op, rs, rt = w >> 26, (w >> 21) & 31, (w >> 16) & 31
    rel = pc + 4 + (((w & 0xFFFF) ^ 0x8000) - 0x8000) * 4
    if op in (4, 5, 6, 7, 0x14, 0x15, 0x16, 0x17):
        return rel
    if op == 1 and rt in (0, 1, 2, 3):
        return rel
    if op in (0x10, 0x11, 0x12) and rs == 8:
        return rel
    if op == 2:
        return ((pc + 4) & 0xF0000000) | ((w & 0x03FFFFFF) << 2)
    return None


def output_name(name, start):
    """PS2Recompiler::generateOutput makeName (ps2_recompiler.cpp:1085), without the entry_ special case."""
    return (sanitize(name) or "func") + "_0x%x" % start


