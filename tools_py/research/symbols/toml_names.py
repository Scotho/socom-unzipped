def is_auto(name):
    return name.startswith(AUTO_PREFIXES)


def name_class(name):
    for p in ("FUN_", "sub_", "thunk_FUN_", "caseD_", "LAB_", "switchD"):
        if name.startswith(p):
            return p.rstrip("_")
    return "entry" if name == "entry" else "named"


def selectors(values):
    out = []
    for v in values:
        name, _, addr = v.rpartition("@")
        out.append((name.strip(), int(addr, 16)) if name else (v.strip(), None))
    return out


def load_call_list():
    text = open(CALL_LIST).read()
    sys_part, stub_part = text.split("#define PS2_STUB_LIST", 1)
    grab = lambda s: set(re.findall(r"X\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)", s))
    return grab(sys_part), grab(stub_part)


def resolves(name, entries):
    """ps2_runtime_calls.h resolveNameWithOptionalLeadingUnderscoreAlias."""
    if not name:
        return False
    if name in entries:
        return True
    if name.startswith("_"):
        return name[1:] in entries
    return ("_" + name) in entries


def sanitize(name):
    """PS2Recompiler::sanitizeFunctionName (ps2_recompiler.cpp:2190 over :49)."""
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if s and not (s[0].isalpha() or s[0] == "_"):
        s = "_" + s
    return s  # keyword / reserved / main prefixes are counted separately in [F]


